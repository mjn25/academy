/* هزینهٔ ارسال کتاب با پست پیشتاز — بالای آستانه، ارسال رایگان می‌شود */
export const shippingCost = 55000;
export const freeShippingOver = 1000000;

export function discountAmount(code: string, subtotal: number): number {
  const d = discountCodes[code];
  if (!d) return 0;
  return d.type === "percent" ? Math.round((subtotal * d.value) / 100) : Math.min(d.value, subtotal);
}
